"""生成示例商品知识文档（Excel + Markdown），供快速体验上传解析与问答。"""
from pathlib import Path

import pandas as pd

OUT_DIR = Path(__file__).parent / "testdata"
OUT_DIR.mkdir(parents=True, exist_ok=True)


def gen_excel():
    rows = [
        ["智能蓝牙耳机 X1", "数码/耳机", "299", "黑色/白色/蓝色", "8小时/32小时", "1年", "支持"],
        ["无线充电宝 20000mAh", "数码/配件", "129", "白色", "—", "1年", "支持"],
        ["智能手环 S3", "数码/穿戴", "199", "黑色/粉色", "14天", "1年", "支持"],
        ["便携榨汁杯", "家电/厨房", "89", "绿色/灰色", "—", "6个月", "支持"],
        ["USB-C 快充数据线 1m", "数码/配件", "19.9", "白色", "—", "3个月", "支持"],
    ]
    df = pd.DataFrame(
        rows,
        columns=["商品名称", "类目", "价格(元)", "颜色", "续航", "保修期", "7天无理由退货"],
    )
    df.to_excel(OUT_DIR / "商品清单.xlsx", index=False)
    print(f"generated {OUT_DIR / '商品清单.xlsx'}")


